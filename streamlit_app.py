def crear_usuario(
    username,
    nombre_visible,
    password
):

    username = normalizar_username(
        username
    )


    nombre_visible = str(
        nombre_visible
    ).strip()


    if not re.fullmatch(
        r"[a-z0-9._-]{3,32}",
        username
    ):

        return (
            False,
            "Usuario inválido.",
            None
        )


    if not nombre_visible:

        return (
            False,
            "Ingresa tu nombre.",
            None
        )


    valida, mensaje = password_valida(
        password
    )


    if not valida:

        return (
            False,
            mensaje,
            None
        )


    salt, password_hash = hash_password(
        password
    )


    with conectar_db() as conexion:

        fila = conexion.execute(
            """
            INSERT INTO portal.usuarios (
                username,
                nombre_visible,
                password_salt,
                password_hash
            )

            VALUES (
                %s,
                %s,
                %s,
                %s
            )

            ON CONFLICT(username)
            DO NOTHING

            RETURNING id
            """,
            (
                username,
                nombre_visible,
                salt,
                password_hash
            )
        ).fetchone()


        if fila is None:

            return (
                False,
                "Ese usuario ya existe.",
                None
            )


        user_id = fila[
            "id"
        ]


        conexion.execute(
            """
            INSERT INTO portal.perfiles (
                user_id,
                cv_texto
            )

            VALUES (
                %s,
                ''
            )

            ON CONFLICT(user_id)
            DO NOTHING
            """,
            (
                user_id,
            )
        )


        conexion.execute(
            """
            INSERT INTO portal.preferencias (
                user_id,
                cargo_deseado,
                modalidad,
                sueldo_minimo,
                acepta_presencial,
                ciudad
            )

            VALUES (
                %s,
                'analista',
                'hibrida',
                1200000,
                FALSE,
                'Santiago'
            )

            ON CONFLICT(user_id)
            DO NOTHING
            """,
            (
                user_id,
            )
        )


    return (
        True,
        "Cuenta creada.",
        user_id
    )


def autenticar_usuario(
    username,
    password
):

    username = normalizar_username(
        username
    )


    with conectar_db() as conexion:

        fila = conexion.execute(
            """
            SELECT
                id,
                username,
                nombre_visible,
                password_salt,
                password_hash

            FROM portal.usuarios

            WHERE username = %s
            """,
            (
                username,
            )
        ).fetchone()


    if fila is None:

        return None


    if not verificar_password(
        password,
        fila[
            "password_salt"
        ],
        fila[
            "password_hash"
        ]
    ):

        return None


    return {

        "id":
            fila[
                "id"
            ],

        "username":
            fila[
                "username"
            ],

        "nombre_visible":
            fila[
                "nombre_visible"
            ]
    }


