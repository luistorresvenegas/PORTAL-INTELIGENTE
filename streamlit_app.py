def password_valida(
    password
):

    if len(
        password
    ) < 8:

        return (
            False,
            "La contraseña debe tener al menos 8 caracteres."
        )


    if not re.search(
        r"[A-Za-zÁÉÍÓÚáéíóúÑñ]",
        password
    ):

        return (
            False,
            "Debe contener al menos una letra."
        )


    if not re.search(
        r"\d",
        password
    ):

        return (
            False,
            "Debe contener al menos un número."
        )


    return (
        True,
        None
    )


def hash_password(
    password,
    salt=None
):

    if salt is None:

        salt = os.urandom(
            16
        )


    password_hash = hashlib.scrypt(
        password.encode(
            "utf-8"
        ),
        salt=salt,
        n=2**14,
        r=8,
        p=1,
        dklen=64
    )


    return (
        salt,
        password_hash
    )


def verificar_password(
    password,
    salt,
    password_hash
):

    _, candidato = hash_password(
        password,
        bytes(
            salt
        )
    )


    return hmac.compare_digest(
        candidato,
        bytes(
            password_hash
        )
    )


