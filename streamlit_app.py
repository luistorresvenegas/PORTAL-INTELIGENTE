def detectar_brechas(
    matches
):

    resultado = []


    for habilidad, datos in matches.items():

        if datos[
            "importancia"
        ] < 4:

            continue


        if datos[
            "candidato"
        ] is None:

            resultado.append(
                {

                    "habilidad":
                        habilidad,

                    "tipo":
                        "AUSENCIA",

                    "deficit":
                        100,

                    "relacion":
                        "SIN MATCH"
                }
            )

            continue


        if (
            habilidad
            in HERRAMIENTAS_ESPECIFICAS
            and
            datos[
                "tipo"
            ]
            not in [
                "EXACTO",
                "EQUIVALENTE"
            ]
        ):

            resultado.append(
                {

                    "habilidad":
                        habilidad,

                    "tipo":
                        "HERRAMIENTA_ESPECIFICA",

                    "deficit":
                        100
                        -
                        datos[
                            "cumplimiento"
                        ],

                    "relacion":
                        datos[
                            "tipo"
                        ]
                }
            )

            continue


        if datos[
            "tipo"
        ] in [
            "TRANSFERIBLE",
            "RELACIONADA"
        ]:

            resultado.append(
                {

                    "habilidad":
                        habilidad,

                    "tipo":
                        "SUSTITUCION",

                    "deficit":
                        100
                        -
                        datos[
                            "cumplimiento"
                        ],

                    "relacion":
                        datos[
                            "tipo"
                        ]
                }
            )

            continue


        if datos[
            "nivel"
        ] < 100:

            resultado.append(
                {

                    "habilidad":
                        habilidad,

                    "tipo":
                        "NIVEL",

                    "deficit":
                        100
                        -
                        datos[
                            "nivel"
                        ],

                    "relacion":
                        datos[
                            "tipo"
                        ]
                }
            )


    return resultado


def penalizacion_brechas(
    brechas
):

    total = 0


    for brecha in brechas:

        if brecha[
            "tipo"
        ] == "AUSENCIA":

            total += 20


        elif brecha[
            "tipo"
        ] == "HERRAMIENTA_ESPECIFICA":

            total += (
                15

                if brecha[
                    "relacion"
                ]
                ==
                "RELACIONADA"

                else 10
            )


        elif brecha[
            "tipo"
        ] == "SUSTITUCION":

            total += min(
                12,
                brecha[
                    "deficit"
                ]
                *
                0.12
            )


        elif brecha[
            "tipo"
        ] == "NIVEL":

            total += (
                brecha[
                    "deficit"
                ]
                *
                0.10
            )


    return min(
        total,
        40
    )


