def alias_presente(
    texto,
    alias
):

    return re.search(
        r"(?<!\w)"
        +
        re.escape(
            normalizar(
                alias
            )
        )
        +
        r"(?!\w)",
        normalizar(
            texto
        )
    ) is not None


def contexto_negado(
    oracion,
    alias
):

    texto = normalizar(
        oracion
    )


    habilidad = normalizar(
        alias
    )


    patrones = [

        rf"\bno\s+(?:manejo|domino|conozco|utilizo|uso)\s+"
        rf"(?:actualmente\s+)?{re.escape(habilidad)}\b",

        rf"\bno\s+tengo\s+(?:experiencia|conocimientos?)\s+"
        rf"(?:en|de|con)?\s*{re.escape(habilidad)}\b",

        rf"\bsin\s+(?:experiencia|conocimientos?|manejo)\s+"
        rf"(?:en|de|con)?\s*{re.escape(habilidad)}\b",

        rf"\b(?:quiero|quisiera|deseo|me\s+interesa)\s+"
        rf"aprender\s+{re.escape(habilidad)}\b",

        rf"\baprender\s+{re.escape(habilidad)}\b"
    ]


    return any(
        re.search(
            patron,
            texto
        )

        for patron
        in patrones
    )


def detectar_nivel_local(
    oracion,
    alias,
    cantidad
):

    texto = normalizar(
        oracion
    )


    habilidad = normalizar(
        alias
    )


    patrones = [

        rf"{re.escape(habilidad)}\s*"
        rf"(?:nivel\s*)?{NIVEL_RE}",

        rf"{NIVEL_RE}\s+"
        rf"(?:en\s+)?{re.escape(habilidad)}",

        rf"(?:nivel|manejo|conocimientos?|experiencia)\s+"
        rf"{NIVEL_RE}\s+"
        rf"(?:en|de|con)?\s*"
        rf"{re.escape(habilidad)}"
    ]


    for patron in patrones:

        coincidencia = re.search(
            patron,
            texto
        )


        if coincidencia:

            for grupo in coincidencia.groups():

                if grupo in NIVELES:

                    return (
                        NIVELES[
                            grupo
                        ],
                        100
                    )


    if cantidad == 1:

        coincidencia = re.search(
            NIVEL_RE,
            texto
        )


        if coincidencia:

            return (
                NIVELES[
                    coincidencia.group(
                        1
                    )
                ],
                90
            )


    return (
        3,
        70
    )


def extraer_habilidades_cv(
    texto
):

    encontradas = {}

    negadas = {}


    for oracion in separar_oraciones(
        texto
    ):

        presentes = []


        for habilidad, aliases in CATALOGO_HABILIDADES.items():

            alias_encontrado = None


            for alias in sorted(
                aliases,
                key=len,
                reverse=True
            ):

                if not alias_presente(
                    oracion,
                    alias
                ):

                    continue


                if (
                    normalizar(
                        alias
                    )
                    ==
                    "bi"
                    and
                    re.search(
                        r"power\s+bi",
                        normalizar(
                            oracion
                        )
                    )
                ):

                    continue


                alias_encontrado = alias

                break


            if alias_encontrado:

                presentes.append(
                    (
                        habilidad,
                        alias_encontrado
                    )
                )


        for habilidad, alias in presentes:

            if contexto_negado(
                oracion,
                alias
            ):

                negadas.setdefault(
                    habilidad,
                    []
                ).append(
                    oracion
                )

                continue


            nivel, confianza = detectar_nivel_local(
                oracion,
                alias,
                len(
                    presentes
                )
            )


            if habilidad not in encontradas:

                encontradas[
                    habilidad
                ] = {

                    "nivel":
                        nivel,

                    "confianza":
                        confianza,

                    "evidencias": [
                        oracion
                    ]
                }

            else:

                encontradas[
                    habilidad
                ][
                    "evidencias"
                ].append(
                    oracion
                )


                # --------------------------------------------------
                # V0.16.3.1
                # La evidencia posterior más fuerte también debe
                # actualizar la confianza, no sólo el nivel.
                # --------------------------------------------------

                encontradas[
                    habilidad
                ][
                    "confianza"
                ] = max(
                    encontradas[
                        habilidad
                    ][
                        "confianza"
                    ],
                    confianza
                )


                if (
                    nivel
                    >
                    encontradas[
                        habilidad
                    ][
                        "nivel"
                    ]
                ):

                    encontradas[
                        habilidad
                    ][
                        "nivel"
                    ] = nivel


    return (
        encontradas,
        negadas
    )


def extraer_campo_linea(
    texto,
    etiquetas
):

    for linea in texto.splitlines():

        linea = linea.strip()


        for etiqueta in etiquetas:

            coincidencia = re.match(
                rf"(?i)^\s*"
                rf"{re.escape(etiqueta)}"
                rf"\s*:\s*(.+?)\s*$",
                linea
            )


            if coincidencia:

                return coincidencia.group(
                    1
                ).strip()


    return None


def procesar_cv(
    texto
):

    nombre = extraer_campo_linea(
        texto,
        [
            "nombre",
            "nombre completo"
        ]
    )


    profesion = extraer_campo_linea(
        texto,
        [
            "profesion",
            "profesión",
            "titulo profesional",
            "título profesional"
        ]
    )


    ciudad = extraer_campo_linea(
        texto,
        [
            "ciudad",
            "residencia",
            "ubicacion",
            "ubicación"
        ]
    )


    if (
        ciudad
        and
        "santiago"
        in normalizar(
            ciudad
        )
    ):

        ciudad = "Santiago"


    experiencia = None


    for patron in [

        r"\b(?:tengo|cuento\s+con|con)\s+"
        r"(\d+)\s*(?:anos|ano)\s+de\s+experiencia\b",

        r"\b(\d+)\s*(?:anos|ano)\s+"
        r"de\s+experiencia\s+"
        r"(?:profesional|laboral)\b"
    ]:

        coincidencia = re.search(
            patron,
            normalizar(
                texto
            )
        )


        if coincidencia:

            experiencia = int(
                coincidencia.group(
                    1
                )
            )

            break


    detalle, negadas = extraer_habilidades_cv(
        texto
    )


    habilidades = {

        habilidad:
            datos[
                "nivel"
            ]

        for habilidad, datos
        in detalle.items()
    }


    campos = [
        nombre,
        profesion,
        ciudad,
        experiencia
    ]


    confianza_campos = (
        sum(
            campo is not None
            for campo in campos
        )
        /
        4
        *
        100
    )


    confianza_skills = (
        sum(
            datos[
                "confianza"
            ]
            for datos
            in detalle.values()
        )
        /
        len(
            detalle
        )

        if detalle
        else 0
    )


    confianza = round(
        confianza_campos
        *
        0.60
        +
        confianza_skills
        *
        0.40,
        2
    )


    return {

        "nombre":
            nombre,

        "profesion":
            profesion,

        "experiencia":
            experiencia,

        "ciudad":
            ciudad,

        "habilidades":
            habilidades,

        "detalle_habilidades":
            detalle,

        "negadas":
            negadas,

        "confianza":
            confianza
    }


