def normalizar(
    texto
):

    texto = str(
        texto
        or
        ""
    ).lower()


    texto = unicodedata.normalize(
        "NFD",
        texto
    )


    texto = "".join(
        caracter
        for caracter in texto
        if unicodedata.category(
            caracter
        )
        !=
        "Mn"
    )


    return texto.strip()


def limitar(
    valor,
    minimo,
    maximo
):

    return max(
        minimo,
        min(
            valor,
            maximo
        )
    )


def separar_oraciones(
    texto
):

    return [
        elemento.strip()

        for elemento
        in re.split(
            r"(?<=[\.\!\?])\s+|\n+",
            texto
        )

        if elemento.strip()
    ]


def normalizar_username(
    username
):

    return normalizar(
        username
    ).replace(
        " ",
        ""
    )


