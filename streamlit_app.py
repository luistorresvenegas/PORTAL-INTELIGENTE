def cumplimiento_nivel(
    nivel_candidato,
    nivel_requerido
):

    if nivel_requerido <= 0:

        return 100


    if nivel_candidato <= 0:

        return 0


    return min(
        100,
        nivel_candidato
        /
        nivel_requerido
        *
        100
    )


def matching_habilidades(
    requeridas,
    candidatas
):

    requeridas_ordenadas = sorted(
        requeridas.items(),
        key=lambda item: (
            -item[1][
                "importancia"
            ],
            -item[1][
                "nivel_requerido"
            ],
            item[0]
        )
    )


    skills_candidato = list(
        candidatas.keys()
    )


    mejor_score = -1

    mejor_asignacion = None


    def buscar(
        indice,
        usadas,
        score,
        asignacion
    ):

        nonlocal mejor_score
        nonlocal mejor_asignacion


        if indice == len(
            requeridas_ordenadas
        ):

            if score > mejor_score:

                mejor_score = score

                mejor_asignacion = list(
                    asignacion
                )

            return


        requerida, datos = requeridas_ordenadas[
            indice
        ]


        asignacion.append(
            (
                requerida,
                None,
                0,
                "SIN MATCH",
                0,
                0,
                0,
                datos
            )
        )


        buscar(
            indice + 1,
            usadas,
            score,
            asignacion
        )


        asignacion.pop()


        for candidata in skills_candidato:

            if candidata in usadas:

                continue


            relacion = relacion_habilidad(
                candidata,
                requerida
            )


            if relacion[
                "similitud"
            ] <= 0:

                continue


            nivel = cumplimiento_nivel(
                candidatas[
                    candidata
                ],
                datos[
                    "nivel_requerido"
                ]
            )


            tipo = relacion[
                "tipo"
            ]


            cumplimiento = (
                nivel
                *
                FACTOR_CUMPLIMIENTO[
                    tipo
                ]
            )


            potencial = (
                relacion[
                    "similitud"
                ]
                +
                nivel
            ) / 2


            aporte = (
                datos[
                    "importancia"
                ]
                *
                (
                    relacion[
                        "similitud"
                    ]
                    *
                    10
                    +
                    cumplimiento
                )
            )


            asignacion.append(
                (
                    requerida,
                    candidata,
                    relacion[
                        "similitud"
                    ],
                    tipo,
                    nivel,
                    cumplimiento,
                    potencial,
                    datos
                )
            )


            buscar(
                indice + 1,
                usadas
                |
                {
                    candidata
                },
                score
                +
                aporte,
                asignacion
            )


            asignacion.pop()


    buscar(
        0,
        set(),
        0,
        []
    )


    resultado = {}


    for (
        requerida,
        candidata,
        similitud,
        tipo,
        nivel,
        cumplimiento,
        potencial,
        datos
    ) in (
        mejor_asignacion
        or []
    ):

        resultado[
            requerida
        ] = {

            "candidato":
                candidata,

            "similitud":
                similitud,

            "tipo":
                tipo,

            "nivel":
                nivel,

            "cumplimiento":
                cumplimiento,

            "potencial":
                potencial,

            "importancia":
                datos[
                    "importancia"
                ],

            "nivel_requerido":
                datos[
                    "nivel_requerido"
                ]
        }


    return resultado


def score_habilidades(
    matches,
    campo
):

    if not matches:

        return 0


    peso = sum(
        datos[
            "importancia"
        ]
        for datos
        in matches.values()
    )


    if peso == 0:

        return 0


    return (
        sum(
            datos[
                campo
            ]
            *
            datos[
                "importancia"
            ]

            for datos
            in matches.values()
        )
        /
        peso
    )


