PESO_ACCION = {

    "postular":
        3,

    "guardar":
        2,

    "ver":
        0.25,

    "rechazar":
        -2
}


def aprender_comportamiento(
    historial
):

    cargos = defaultdict(
        float
    )

    modalidades = defaultdict(
        float
    )

    ciudades = defaultdict(
        float
    )

    habilidades = defaultdict(
        float
    )


    interacciones = 0


    for evento in historial:

        accion = normalizar(
            evento.get(
                "accion"
            )
        )


        if accion not in PESO_ACCION:

            continue


        interacciones += 1


        peso = PESO_ACCION[
            accion
        ]


        cargo = normalizar_cargo(
            evento.get(
                "cargo"
            )
        )


        modalidad = normalizar(
            evento.get(
                "modalidad"
            )
        )


        ciudad = normalizar(
            evento.get(
                "ciudad"
            )
        )


        motivo = normalizar(
            evento.get(
                "motivo"
            )
        )


        if peso > 0:

            cargos[
                cargo
            ] += peso


            modalidades[
                modalidad
            ] += peso


            ciudades[
                ciudad
            ] += peso


            for skill in evento.get(
                "habilidades",
                []
            ):

                habilidades[
                    canon_skill(
                        skill
                    )
                ] += peso


        elif accion == "rechazar":

            if motivo == "cargo":

                cargos[
                    cargo
                ] += peso


            elif motivo == "modalidad":

                modalidades[
                    modalidad
                ] += peso


            elif motivo == "ubicacion":

                ciudades[
                    ciudad
                ] += peso


    confianza = min(
        100,
        interacciones
        /
        8
        *
        100
    )


    return {

        "interacciones":
            interacciones,

        "confianza":
            round(
                confianza,
                2
            ),

        "habilitado":
            (
                interacciones >= 3
                and
                confianza >= 40
            ),

        "afinidad_cargos":
            dict(
                cargos
            ),

        "afinidad_modalidades":
            dict(
                modalidades
            ),

        "afinidad_ciudades":
            dict(
                ciudades
            ),

        "afinidad_habilidades":
            dict(
                habilidades
            )
    }


