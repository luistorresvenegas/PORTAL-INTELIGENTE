def actualizar_password(
    user_id,
    nueva_password
):

    valida, mensaje = password_valida(
        nueva_password
    )


    if not valida:

        return (
            False,
            mensaje
        )


    salt, password_hash = hash_password(
        nueva_password
    )


    with conectar_db() as conexion:

        resultado = conexion.execute(
            """
            UPDATE portal.usuarios

            SET
                password_salt = %s,
                password_hash = %s

            WHERE id = %s
            """,
            (
                salt,
                password_hash,
                user_id
            )
        )


    return (
        resultado.rowcount
        ==
        1,
        (
            "Contraseña actualizada."
            if resultado.rowcount
            ==
            1
            else
            "No se pudo actualizar."
        )
    )


